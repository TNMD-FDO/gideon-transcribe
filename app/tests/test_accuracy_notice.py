"""v1.248.0: the notice says a Transcript may contain errors, names the
models that made it, and is shown on the transcript's page.

The rules checked here: a Transcript that was not translated carries the
Transcription notice, or the wording for speakers told apart when a model
told them apart, each naming the model that wrote the words (and the one
that told the speakers apart) by its whole name with no version mark; a
Transcript Qwen3-ASR wrote is never said to be Whisper's, on the shipped
wording or on one an office kept from before; a translated Transcript keeps
its own notice and gains the speakers' sentence when its speakers were told
apart; an emptied wording falls back or adds nothing; the upgrade forgets a
stored copy of the old shipped wording and leaves an office's own; the
Notices page lists the two new texts; and the transcript's page carries the
notice above the words.
"""

from __future__ import annotations

import importlib

import pytest
from core import exports, settings_store
from core.jobs import Segment, Transcript
from core.models import User
from core.recordings import Batch, MediaState, Recording
from django.apps import apps as live_apps
from tests.helpers import signed_in

PASSWORD = "a-long-enough-password"
OLD = (
    "Automatic transcription by Whisper {model}. Corrections made by staff are "
    "marked. This is not a certified transcript."
)
WHISPER = {"model": "large-v3-turbo"}
QWEN = {
    "recogniser": "qwen3-asr",
    "model": "qwen3-asr-1.7b",
    "recogniser_version": "7278e1e7aabbccdd",
}
NEMOTRON = {"diarize": True, "diarizer": "nemotron", "diarizer_version": "f667ed73aa"}


@pytest.fixture
def person(db):
    return User.objects.from_directory("jsmith", display_name="J Smith")


def a_transcript(person, used=None, diarize=False, **fields):
    recording = Recording.objects.create(
        batch=Batch.objects.create(user=person),
        user=person,
        title="Interview",
        original_filename="interview.m4a",
        media_state=MediaState.READY,
        playback_ready=True,
        diarize=diarize,
    )
    recording.folder.mkdir(parents=True, exist_ok=True)
    transcript = Transcript.objects.create(
        recording=recording,
        language=fields.pop("language", "en"),
        provenance={"one": {"settings_used": used}} if used is not None else {},
        **fields,
    )
    Segment.objects.create(
        transcript=transcript, start=0, end=4, text="Good morning.", speaker="Rowe"
    )
    return transcript


# The wording ------------------------------------------------------------------


def test_a_plain_transcript_says_it_may_contain_errors(person):
    notice = exports.notice_for(a_transcript(person, {**WHISPER, "diarize": False}))
    assert notice == (
        "Transcription is generated by an AI model (Whisper large-v3-turbo) and "
        "may contain errors. Confirm accuracy against the recording. This is not "
        "a certified transcript."
    )


def test_speakers_told_apart_names_both_models(person):
    notice = exports.notice_for(a_transcript(person, {**WHISPER, **NEMOTRON}))
    assert notice == (
        "Transcription and speaker separation are generated by AI models "
        "(Whisper large-v3-turbo and Nemotron 3 Diarization) and may contain "
        "errors. Confirm accuracy against the recording. This is not a certified "
        "transcript."
    )


def test_a_qwen_transcript_is_never_said_to_be_whispers(person):
    notice = exports.notice_for(a_transcript(person, {**QWEN, **NEMOTRON}))
    assert "(Qwen3-ASR 1.7B and Nemotron 3 Diarization)" in notice
    assert "Whisper" not in notice
    # The version marks are the processing record's, not the notice's.
    assert "7278e1e7" not in notice and "f667ed73" not in notice
    plain = exports.notice_for(a_transcript(person, {**QWEN, "diarize": False}))
    assert "an AI model (Qwen3-ASR 1.7B)" in plain and "Whisper" not in plain


def test_a_wording_kept_from_before_is_mended_as_it_is_filled(person):
    settings_store.set_to("transcription_notice", OLD.replace("marked.", "shown."))
    settings_store.set_to("transcription_notice_speakers", "")
    by_qwen = exports.notice_for(a_transcript(person, {**QWEN, **NEMOTRON}))
    assert by_qwen.startswith("Automatic transcription by Qwen3-ASR 1.7B. ")
    by_whisper = exports.notice_for(a_transcript(person, {**WHISPER}))
    assert by_whisper.startswith("Automatic transcription by Whisper large-v3-turbo. ")
    assert "Whisper Whisper" not in by_whisper


def test_the_recording_decides_where_no_run_says(person):
    asked = a_transcript(person, None, diarize=True)
    assert exports.told_apart(asked) is True
    # A result from before the choice of model existed is pyannote's.
    assert "(Whisper and pyannote community-1)" in exports.notice_for(asked)
    assert exports.told_apart(a_transcript(person, None, diarize=False)) is False
    # A Run that says it was not asked to is believed over the Recording.
    said_no = a_transcript(person, {**WHISPER, "diarize": False}, diarize=True)
    assert exports.told_apart(said_no) is False


def test_a_translation_keeps_its_notice_and_gains_the_speakers_sentence(person):
    plain = exports.notice_for(
        a_transcript(
            person, {**WHISPER, "diarize": False}, task_run="translate", language="es"
        )
    )
    assert plain == (
        "Machine translation to English from Spanish by Whisper large-v3-turbo. "
        "The original-language text was not kept. This is not a certified "
        "translation."
    )
    apart = exports.notice_for(
        a_transcript(
            person, {**WHISPER, **NEMOTRON}, task_run="translate", language="es"
        )
    )
    assert apart == plain + (
        " Speaker separation is generated by an AI model (Nemotron 3 Diarization) "
        "and may contain errors. Confirm accuracy against the recording."
    )


def test_an_emptied_wording_falls_back_or_adds_nothing(person):
    settings_store.set_to("transcription_notice_speakers", "")
    settings_store.set_to("speaker_notice", "")
    notice = exports.notice_for(a_transcript(person, {**WHISPER, **NEMOTRON}))
    assert notice.startswith("Transcription is generated by an AI model (Whisper")
    translated = exports.notice_for(
        a_transcript(
            person, {**WHISPER, **NEMOTRON}, task_run="translate", language="es"
        )
    )
    assert translated.endswith("This is not a certified translation.")


# The upgrade --------------------------------------------------------------------


def test_the_upgrade_forgets_a_stored_copy_of_the_old_shipped_wording(db):
    step = importlib.import_module(
        "core.migrations.0116_transcription_notice_as_shipped"
    )
    settings_store.set_to("transcription_notice", OLD)
    step.forget_the_old_default(live_apps, None)
    settings_store.forget("transcription_notice")
    assert settings_store.get("transcription_notice").startswith(
        "Transcription is generated by an AI model ({model})"
    )


def test_the_upgrade_leaves_an_offices_own_wording(db):
    step = importlib.import_module(
        "core.migrations.0116_transcription_notice_as_shipped"
    )
    own = "Draft transcript by {model}. Not for filing."
    settings_store.set_to("transcription_notice", own)
    step.forget_the_old_default(live_apps, None)
    settings_store.forget("transcription_notice")
    assert settings_store.get("transcription_notice") == own


# The pages ----------------------------------------------------------------------


def test_the_notices_page_lists_the_two_new_texts(db, client):
    admin = User.objects.create_local_admin("asker", PASSWORD)
    signed_in(client, admin)
    page = client.get("/panel/settings/notices").content.decode()
    assert "Transcription notice, speakers told apart" in page
    assert "Sentence added when speakers were told apart" in page
    assert "generated by AI models ({model} and {voices})" in page


def test_the_transcripts_page_carries_the_notice_above_the_words(person, client):
    transcript = a_transcript(person, {**QWEN, **NEMOTRON})
    signed_in(client, person)
    page = client.get(f"/recording/{transcript.recording.pk}").content.decode()
    assert '<p id="transcript-notice" class="transcript-notice">' in page
    assert (
        "Transcription and speaker separation are generated by AI models "
        "(Qwen3-ASR 1.7B and Nemotron 3 Diarization) and may contain errors."
    ) in page
    # Above the words, and inside the column that scrolls.
    assert page.index('id="transcript-notice"') < page.index('<ol id="transcript"')


def test_the_exports_print_the_same_notice(person):
    transcript = a_transcript(person, {**QWEN, **NEMOTRON})
    text = exports.plain_text(transcript.recording)
    assert exports.notice_for(transcript) in text
